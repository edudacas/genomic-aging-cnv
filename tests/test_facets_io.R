source("facets_grch38.R")
source("facets_segments.R")
source("facets_io.R")
root <- tempfile("facets-io-")
dir.create(root)
counts <- data.frame(Chromosome="chr1",Position=c(20,30,40),NOR.DP=100,NOR.RD=50,
    TUM.DP=100,TUM.RD=50,catalog_kind="SNP",masked=FALSE,catalog_row=c(2,4,8))
bias <- data.frame(snp_index=paste0("1_",counts$Position),correction_bias=0,
    bias_unit="ln_alt_ref",allelic_pseudocount=1/6)
cfg <- c(reference_build="GRCh38",ndepth=20,ndepthmax=2000,het_threshold=.1,
    snp_neighborhood=0,initial_cval=25,final_cval=150,gamma=.25,min_nhet=15,seed=0,
    allelic_pseudocount=format(1/6,digits=17),sample_het_min_depth=50,het_scale="TRUE",delta_cn=0)
write_tsv <- function(x,name) write.table(x,file.path(root,name),sep="\t",quote=FALSE,row.names=FALSE)
write_tsv(counts,"matrix.tsv")
write_tsv(bias,"bias.tsv")
write_tsv(data.frame(key=names(cfg),value=unname(cfg)),"config.tsv")
write_tsv(data.frame(source="chr1",native="1"),"map.tsv")
args <- as.list(file.path(root,c("matrix.tsv","bias.tsv","config.tsv","map.tsv")))
inputs <- do.call(read_joint_files,args)
stopifnot(is.numeric(inputs$bias$correction_bias),is.logical(inputs$counts$masked))
engine <- new.env()
engine$procSnps <- function(x,...) data.frame(chrom=1,maploc=x$Position,rCountT=x$TUM.DP)
engine$counts2logROR <- function(x,...) transform(x,cnlr=c(0,.02,-.01),valor=.1,het=1)
engine$segsnps <- function(x,...) list(jointseg=transform(x,seg=1))
engine$procSample <- function(x,...) list(jointseg=x$jointseg)
result <- do.call(run_joint_files,c(args,list(output=file.path(root,"ok"),engine=engine)))
stopifnot(file.exists(file.path(root,"ok","COMPLETE.txt")))
must_fail <- function(expr) stopifnot(inherits(tryCatch({force(expr);NULL},error=identity),"error"))
must_fail(do.call(run_joint_files,c(args,list(output=file.path(root,"ok"),engine=engine))))
engine$procSample <- function(...) stop("synthetic engine failure")
must_fail(do.call(run_joint_files,c(args,list(output=file.path(root,"failed"),engine=engine))))
stopifnot(file.exists(file.path(root,"failed","FAILURE.txt")),
          !file.exists(file.path(root,"failed","COMPLETE.txt")))
write_tsv(bias[FALSE,],"bias.tsv")
inputs <- do.call(read_joint_files,args)
stopifnot(nrow(inputs$bias)==0,is.numeric(inputs$bias$correction_bias))
cfg["het_scale"] <- "system('false')"
write_tsv(data.frame(key=names(cfg),value=unname(cfg)),"config.tsv")
must_fail(do.call(read_joint_files,args))
unlink(root,recursive=TRUE)
cat("FACETS_IO_CONTRACT_PASS; native_engine_tested=FALSE\n")
